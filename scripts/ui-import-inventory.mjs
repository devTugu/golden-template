#!/usr/bin/env node
/**
 * Build md/ui-inventory.md — which composed/default-space modules are referenced.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const uiRoot = path.join(root, 'packages/ui/src');

const uiDocsFeatures = process.env.UI_DOCS_FEATURES_DIR
  ? path.resolve(process.env.UI_DOCS_FEATURES_DIR)
  : path.join(root, '../golden-template-ui-docs/frontend/src/features/docs');

const SCAN_DIRS = [
  path.join(root, 'frontend/app'),
  path.join(root, 'frontend/src'),
  path.join(root, 'packages/api'),
  path.join(root, 'packages/hooks'),
  path.join(root, 'packages/types'),
  path.join(root, 'packages/utils'),
  path.join(root, 'packages/ui-charts'),
  path.join(root, 'packages/ui-code'),
  path.join(root, 'packages/ui-motion-3d'),
  ...(fs.existsSync(uiDocsFeatures) ? [uiDocsFeatures] : []),
];

const IMPORT_RE =
  /@default\/ui\/(composed|default-space)\/([a-z0-9-]+(?:\/[a-z0-9.-]+)*)/gi;

function walkFiles(dir, out = []) {
  if (!fs.existsSync(dir)) return out;
  for (const ent of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, ent.name);
    if (ent.isDirectory()) {
      if (ent.name === 'node_modules' || ent.name === '.next') continue;
      walkFiles(full, out);
    } else if (/\.(tsx?|jsx?|mjs)$/.test(ent.name)) {
      out.push(full);
    }
  }
  return out;
}

function collectUsedImports() {
  const used = {
    frontendApp: new Set(),
    frontendSrc: new Set(),
    packages: new Set(),
    docs: new Set(),
  };

  for (const base of SCAN_DIRS) {
    for (const file of walkFiles(base)) {
      const text = fs.readFileSync(file, 'utf8');
      let m;
      IMPORT_RE.lastIndex = 0;
      while ((m = IMPORT_RE.exec(text)) !== null) {
        const key = `${m[1]}/${m[2]}`;
        const rel = path.relative(root, file);
        if (rel.startsWith('frontend/app/')) {
          used.frontendApp.add(key);
        } else if (
          rel.startsWith('frontend/src/features/docs/') ||
          (fs.existsSync(uiDocsFeatures) &&
            file.startsWith(uiDocsFeatures + path.sep))
        ) {
          used.docs.add(key);
        } else if (rel.startsWith('frontend/src/')) {
          used.frontendSrc.add(key);
        } else {
          used.packages.add(key);
        }
      }
    }
  }
  return used;
}

function listUiModules(layer) {
  const dir = path.join(uiRoot, layer);
  if (!fs.existsSync(dir)) return [];
  const modules = [];
  for (const category of fs.readdirSync(dir, { withFileTypes: true })) {
    if (!category.isDirectory()) continue;
    const catPath = path.join(dir, category.name);
    for (const file of fs.readdirSync(catPath)) {
      if (!file.endsWith('.tsx')) continue;
      const base = file.replace(/\.tsx$/, '');
      modules.push(`${layer}/${category.name}/${base}`);
    }
  }
  return modules.sort();
}

function isModuleUsed(modulePath, used) {
  const parts = modulePath.split('/');
  const layer = parts[0];
  const category = parts[1];
  const file = parts[2];
  const prefixes = [
    `${layer}/${category}/${file}`,
    `${layer}/${category}`,
  ];
  const sets = [
    used.frontendApp,
    used.frontendSrc,
    used.packages,
    used.docs,
  ];
  for (const set of sets) {
    for (const u of set) {
      if (prefixes.some((p) => u === p || u.startsWith(`${p}/`))) {
        return true;
      }
      if (u.startsWith(`${layer}/${category}/`) && u.includes(file)) {
        return true;
      }
    }
  }
  return false;
}

function usageFlags(modulePath, used) {
  const check = (set) => {
    const parts = modulePath.split('/');
    const layer = parts[0];
    const category = parts[1];
    const file = parts[2];
    for (const u of set) {
      if (
        u === modulePath ||
        u === `${layer}/${category}/${file}` ||
        u.startsWith(`${layer}/${category}/${file}`) ||
        (u.startsWith(`${layer}/${category}/`) && u.endsWith(file))
      ) {
        return true;
      }
    }
    return false;
  };
  return {
    app: check(used.frontendApp),
    src: check(used.frontendSrc),
    pkg: check(used.packages),
    docs: check(used.docs),
  };
}

function main() {
  const used = collectUsedImports();
  const lines = [
    '# UI package import inventory',
    '',
    `Generated by \`node scripts/ui-import-inventory.mjs\` on ${new Date().toISOString().slice(0, 10)}.`,
    '',
    'Scope: `packages/ui/src/composed/` and `default-space/` demo modules (one `.tsx` file = one row).',
    '',
    'Legend: **app** = `frontend/app`; **src** = `frontend/src`; **docs** = `golden-template-ui-docs/frontend/src/features/docs` (sibling clone); **pkg** = other workspace packages.',
    '',
  ];

  for (const layer of ['composed', 'default-space']) {
    const modules = listUiModules(layer);
    let unusedCount = 0;
    lines.push(`## ${layer}/`, '');
    lines.push(
      '| Module | app | src | pkg | docs | Status |',
      '|--------|-----|-----|-----|------|--------|',
    );
    for (const mod of modules) {
      const flags = usageFlags(mod, used);
      const any =
        flags.app || flags.src || flags.pkg || flags.docs;
      if (!any) unusedCount += 1;
      const yn = (v) => (v ? 'yes' : '—');
      lines.push(
        `| \`${mod}\` | ${yn(flags.app)} | ${yn(flags.src)} | ${yn(flags.pkg)} | ${yn(flags.docs)} | ${any ? 'used' : '**unused**'} |`,
      );
    }
    lines.push('', `**Summary:** ${modules.length} files, ${unusedCount} unused.`, '');
  }

  const outPath = path.join(root, 'md/ui-inventory.md');
  fs.writeFileSync(outPath, lines.join('\n'));
  console.log(`Wrote ${outPath}`);
}

main();
